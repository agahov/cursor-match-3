// Deterministic, engine-free seeded PRNG (ADR 0004, A12). Injected into the
// world in `app/`; systems must use this instead of global Math.random so rule
// tests and E2E are reproducible.
export type Rng = () => number

export function mulberry32(seed: number): Rng {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
